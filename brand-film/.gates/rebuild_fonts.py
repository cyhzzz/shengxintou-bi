"""rebuild_fonts.py — rebuild the three Noto Sans SC woff2 subsets.

The film's subsets were cut before the desensitisation pass and contain no
asterisk-like glyph, so every masked value (××× / ××%) would fall back to a
tofu box. This re-instances the system variable font
(C:/Windows/Fonts/NotoSansSC-VF.ttf) at the three declared weights and
re-subsets to the on-screen charset:

    src/chars.txt (regenerated by build.py)  + printable ASCII
    + the film's punctuation set              + mask glyphs  × ＊ *

Idempotent. Run after build.py whenever on-screen text changes:
    .venv/Scripts/python.exe .gates/rebuild_fonts.py
"""
import os

from fontTools.ttLib import TTFont
from fontTools.subset import Options, Subsetter
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = 'C:/Windows/Fonts/NotoSansSC-VF.ttf'
OUT = os.path.join(ROOT, 'film', 'assets', 'fonts')
WEIGHTS = (400, 700, 900)

# punctuation build.py adds on top of the CJK range, plus what the mask needs
PUNCT = '：·｜（）「」，。✓→←↑↓％'
MASK_GLYPHS = '×＊*'
ASCII = ''.join(chr(c) for c in range(0x20, 0x7F))


def charset():
    chars = set(open(os.path.join(ROOT, 'src', 'chars.txt'), encoding='utf-8').read())
    chars |= set(ASCII) | set(PUNCT) | set(MASK_GLYPHS)
    chars.discard('\n')
    return ''.join(sorted(chars))


def main():
    text = charset()
    print(f'charset: {len(text)} chars')
    for w in WEIGHTS:
        f = TTFont(SRC)
        instantiateVariableFont(f, {'wght': w}, inplace=True)
        opt = Options()
        opt.flavor = 'woff2'
        opt.name_IDs = ['*']
        opt.notdef_outline = True
        opt.recalc_bounds = True
        ss = Subsetter(options=opt)
        ss.populate(text=text)
        ss.subset(f)
        dst = os.path.join(OUT, f'sans-{w}.woff2')
        f.save(dst)
        print(f'{os.path.getsize(dst) / 1024:5.1f} KB  sans-{w}.woff2')


if __name__ == '__main__':
    main()
